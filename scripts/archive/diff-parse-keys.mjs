const count = (txt, k) => (txt.split(k) ?? []).length - 1;

const rec = fs.readFileSync(REC, "utf8");
const tmp = fs.mkdtempSync(path.join(process.env.TEMP, "tplkey-"));
execFileSync("tar", ["-xf", TPL, "-C", tmp], { stdio: "pipe" });
const tpl = fs.readFileSync(path.join(tmp, "Metadata", "plate_1.gcode"), "utf8");
fs.rmSync(tmp, { recursive: true, force: true });

console.log("key".padEnd(30), "TPL".padStart(5), "REC".padStart(5), "DIFF");
for (const k of keys) {
  const a = count(tpl, k),
    b = count(rec, k);
  if (a !== b)
    console.log(
      k.padEnd(30),
      String(a).padStart(5),
      String(b).padStart(5),
      String(b - a).padStart(5),
    );
}
console.log("\n-- keys where template >= 1 and recovery = 0 --");
for (const k of keys) {
  const a = count(tpl, k),
    b = count(rec, k);
  if (a >= 1 && b === 0) console.log("  MISSING:", JSON.stringify(k), "tpl=" + a);
}
