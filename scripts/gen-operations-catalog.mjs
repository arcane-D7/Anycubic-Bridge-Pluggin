#!/usr/bin/env node
/**
 * S9.18-001 — generate schemas/frontend-operations.json from the shared
 * registry core (single source of truth; the artifact is checked in and
 * `tests/frontend-operations-catalog.test.mjs` verifies it byte-equals a
 * fresh derivation). Node >= 22 (type stripping) — the core is pure.
 *
 * The artifact is the catalogue protocol for the NEXT provider-loop worker:
 * every entry declares `executionLocation: "frontend"` explicitly, because
 * these reversible UI operations are NEVER backend-executed (the broker
 * catalog, OPERATION_SCHEMA_VERSION=1, truthfully excludes them — see
 * docs/operations-catalog-s9-18-001.md §6).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const coreUrl = pathToFileURL(
  path.join(root, "apps", "editor", "src", "state", "operation-registry-core.ts"),
);
const core = await import(`${coreUrl.href}?gen=${Date.now()}`);

const catalog = {
  $comment:
    "Generated by scripts/gen-operations-catalog.mjs from apps/editor/src/state/operation-registry-core.ts — do not hand-edit.",
  schemaVersion: core.OPERATION_CATALOG_VERSION,
  executionLocation: "frontend",
  operations: core.OPERATIONS.map((op) => ({
    id: op.id,
    kind: op.kind,
    schemaVersion: op.schemaVersion,
    reversible: op.reversible,
    executionLocation: op.executionLocation,
    description: op.description,
    inputSchema: op.inputSchema,
    eligibility: op.eligibility,
    exclusions: op.exclusions,
  })),
};

// Format with the repo's own prettier config (parser "json") so the checked-in
// artifact byte-equals both a fresh derivation AND `prettier --check .`.
// prettier is a root devDependency (same version the format gate uses).
import prettier from "prettier";
const prettierConfig = { ...(await prettier.resolveConfig(root)), parser: "json" };
const text = await prettier.format(`${JSON.stringify(catalog, null, 2)}\n`, prettierConfig);

const outPath = path.join(root, "schemas", "frontend-operations.json");
mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, text, "utf8");
console.log(
  `wrote ${path.relative(root, outPath)} (${catalog.operations.length} operations, schemaVersion ${catalog.schemaVersion}, executionLocation ${catalog.executionLocation})`,
);
