        // PTR _anyprint._tcp.local (adivinhação)
        Send(new byte[] {0x00,0x00,0x01,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x09,0x5f,0x61,0x6e,0x79,0x70,0x72,0x69,0x6e,0x74,0x04,0x5f,0x74,0x63,0x70,0x05,0x6c,0x6f,0x63,0x61,0x6c,0x00,0x00,0x0c,0x00,0x01});
