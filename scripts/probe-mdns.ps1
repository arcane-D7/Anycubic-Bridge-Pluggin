using System;
using System.Net;
using System.Net.Sockets;
using System.Text;
using System.Collections.Generic;

public class MdnsProbe {
    static Socket s;

    static void Send(byte[] pkt) {
        s.SendTo(pkt, new IPEndPoint(IPAddress.Parse("224.0.0.251"), 5353));
    }

    static void Listen(int ms, HashSet<string> seen) {
        s.ReceiveTimeout = ms;
        var b = new byte[16384];
        EndPoint ep = new IPEndPoint(IPAddress.Any, 0);
        try {
            while (true) {
                int n = s.ReceiveFrom(b, ref ep);
                var raw = new byte[n];
                Array.Copy(b, raw, n);
                var sb = new StringBuilder();
                foreach (var c in Encoding.UTF8.GetString(raw)) sb.Append((c >= 32 && c < 127) ? c : '.');
                var key = ep + "|" + n;
                if (seen.Add(key)) Console.WriteLine(ep.ToString() + " len=" + n + " :: " + sb.ToString());
            }
        } catch (SocketException) { }
    }

    public static void Run() {
        s = new Socket(AddressFamily.InterNetwork, SocketType.Dgram, ProtocolType.Udp);
        s.Bind(new IPEndPoint(IPAddress.Any, 0));
        // mDNS multicast: membership via AddMembership (JoinMulticastGroup doesn't exist on raw Socket)
        s.SetSocketOption(SocketOptionLevel.IP, SocketOptionName.MulticastLoopback, true);
        s.SetSocketOption(SocketOptionLevel.IP, SocketOptionName.AddMembership, new MulticastOption(IPAddress.Parse("224.0.0.251")));
        var seen = new HashSet<string>();
        // PTR _hap._tcp.local
        Send(new byte[] {0x00,0x00,0x01,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x04,0x5f,0x68,0x61,0x70,0x04,0x5f,0x74,0x63,0x70,0x05,0x6c,0x6f,0x63,0x61,0x6c,0x00,0x00,0x0c,0x00,0x01});
        // PTR _anycubic._tcp.local
        Send(new byte[] {0x00,0x00,0x01,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x09,0x5f,0x61,0x6e,0x79,0x63,0x75,0x62,0x69,0x63,0x04,0x5f,0x74,0x63,0x70,0x05,0x6c,0x6f,0x63,0x61,0x6c,0x00,0x00,0x0c,0x00,0x01});
