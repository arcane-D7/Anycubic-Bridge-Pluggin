// S9.18-001 — schemas/frontend-operations.json artifact honesty.
// The committed artifact must byte-equal a fresh derivation from the shared
// registry core (single source of truth — regenerate via
// `node scripts/gen-operations-catalog.mjs` on any catalog change), and its
// shape must declare the explicit frontend execution contract.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const require = createRequire(import.meta.url);
const { pathToFileURL } = require("node:url");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = path.join(root, "schemas", "frontend-operations.json");
const artifactText = readFileSync(artifactPath, "utf8");
const artifact = JSON.parse(artifactText);

const coreUrl = pathToFileURL(
  path.join(root, "apps", "editor", "src", "state", "operation-registry-core.ts"),
);
const core = await import(`${coreUrl.href}?key=${Date.now()}`);

function deriveArtifact() {
  return {
    $comment:
      "Generated by scripts/gen-operations-catalog.mjs from apps/editor/src/state/operation-registry-core.ts — do not hand-edit.",
    schemaVersion: core.OPERATION_CATALOG_VERSION,
    executionLocation: "frontend",
    operations: core.OPERATIONS.map((op) => ({
      id: op.id,
      kind: op.kind,
      schemaVersion: op.schemaVersion,
      reversible: op.reversible,
      executionLocation: op.executionLocation,
      description: op.description,
      inputSchema: op.inputSchema,
      eligibility: op.eligibility,
      exclusions: op.exclusions,
    })),
  };
}

test("artifact: committed file is byte-identical to the derived catalog (regenerate message on drift)", async () => {
  const derived = await prettier.format(`${JSON.stringify(deriveArtifact(), null, 2)}\n`, {
    ...(await prettier.resolveConfig(root)),
    parser: "json",
  });
  assert.equal(
    artifactText,
    derived,
    "schemas/frontend-operations.json is stale — run `node scripts/gen-operations-catalog.mjs` and commit the regenerated file",
  );
});

test("artifact: shape declares the explicit frontend execution contract", () => {
  assert.equal(artifact.schemaVersion, 1);
  assert.equal(artifact.executionLocation, "frontend");
  assert.ok(Array.isArray(artifact.operations));
  assert.deepEqual(
    artifact.operations.map((op) => op.id),
    ["workspace.navigate", "scene.select"],
  );
  for (const op of artifact.operations) {
    assert.equal(op.executionLocation, "frontend", op.id);
    assert.equal(op.reversible, true, op.id);
    assert.equal(op.schemaVersion, 1, op.id);
    assert.equal(op.inputSchema.additionalProperties, false, op.id);
    assert.ok(Array.isArray(op.eligibility), op.id);
    assert.ok(Array.isArray(op.exclusions), op.id);
    assert.ok(op.exclusions.length > 0, `${op.id} must document exclusions honestly`);
    assert.ok(op.kind === "workspace" || op.kind === "scene", op.id);
  }
});
